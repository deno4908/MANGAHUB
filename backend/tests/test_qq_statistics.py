def test_rating_delete_removes_both_aliases_for_only_the_current_user(hints, monkeypatch):
    db = DB({"ratings": rating_rows()})
    monkeypatch.setattr(ratings, "enforce_user_action_limit", lambda *args, **kwargs: None)
    asyncio.run(ratings.remove_rating(None, NATIVE, user={"id": "a"}, db=db))
