OLD = "vo-trong-game-cua-toi"
NATIVE = OLD + "-12345"


class DB:
    def __init__(self, rows):
        self.rows, self.reads, self.writes = rows, [], []

    def table(self, table):
        db = self

        class Query:
            def __init__(self):
                self.filters, self.operation, self.value = {}, "read", None
                self.sort, self.maximum = None, None

            def select(self, *args): return self
            def eq(self, key, value):
                self.filters[key] = [value]
                return self
            def in_(self, key, values):
                self.filters[key] = list(values)
                return self
            def order(self, key, desc=False):
                self.sort = (key, desc)
                return self
            def limit(self, count):
                self.maximum = count
                return self
            def maybe_single(self): return self
            def delete(self):
                self.operation = "delete"
                return self
            def upsert(self, value, **kwargs):
                self.operation, self.value = "upsert", value
                return self
            def execute(self):
                if self.operation != "read":
                    db.writes.append((table, self.operation, self.value, self.filters))
                    return SimpleNamespace(data=[])
                db.reads.append((table, self.filters))
                rows = [row for row in db.rows.get(table, [])
                    if all(row.get(key) in values for key, values in self.filters.items())]
                if self.sort:
                    rows.sort(key=lambda row: row[self.sort[0]], reverse=self.sort[1])
                return SimpleNamespace(data=rows[:self.maximum])
        return Query()


@pytest.fixture
def hints(monkeypatch):
    values = {}
    reads = []
    def get_many(keys):
        keys = list(keys)
        reads.append(keys)
        return {key: values.get(key) for key in keys}
    monkeypatch.setattr(stats.cache, "get_many", get_many)
    monkeypatch.setattr(stats.cache, "set_many", lambda data, **kwargs: values.update(data))
    monkeypatch.setattr(qq, "run_live", AsyncMock(side_effect=AssertionError("No source reads for stats")))
    manga._rating_cache.clear()
    # This is exactly the hint generated by a normal listing; no new lookup.
    qq._item({"id": "12345", "url": f"https://truyenqqko.com/truyen-tranh/{NATIVE}",
              "title": "Vợ Trong Game Của Tôi", "cover_urls": ["https://example.org/a.jpg"]})
    yield values, reads
    manga._rating_cache.clear()


def test_verified_qq_items_combine_old_and_new_view_counters_without_io(hints):
    values, reads = hints
    item = {"slug": NATIVE, "source": "truyenqq", "name": "Vợ Trong Game Của Tôi"}
    manga._otruyen_apply_local_views(item, {OLD: 83, NATIVE: 7, "unrelated-1": 900})
    assert item["views"] == item["local_view_count"] == item["view_count"] == 90
    assert not reads
    unrelated = {"slug": NATIVE, "source": "uploaded", "name": item["name"]}
    manga._otruyen_apply_local_views(unrelated, {OLD: 83, NATIVE: 7})
    assert unrelated["views"] == 7


def test_cached_aliases_use_one_batch_and_never_guess_unknown_numeric_suffixes(hints):
    values, reads = hints
    aliases = stats.cached_aliases([NATIVE, OLD, "unknown-book-123", "local-upload-3"])
    assert aliases[NATIVE] == aliases[OLD] == [NATIVE, OLD]
    assert "unknown-book-123" not in aliases
    assert "local-upload-3" not in aliases
    assert len(reads) == 1
    # No fuzzy title matching, and unrelated hint keys cannot link statistics.
    values["truyenqq:cover-hint:almost-the-same"] = values["truyenqq:cover-hint:" + NATIVE]
    assert not stats.cached_aliases(["almost-the-same"])
    reads.clear()
    assert not stats.cached_aliases(["564617f3-fdb8-4024-86d6-7bd0456fe745"])
    assert not reads


def rating_rows():
    return [{"manga_slug": OLD, "user_id": "a", "score": 5, "updated_at": "2026-01-01"},
            {"manga_slug": NATIVE, "user_id": "a", "score": 3, "updated_at": "2026-02-01"},
            {"manga_slug": OLD, "user_id": "b", "score": 4, "updated_at": "2026-01-01"}]


def test_single_and_batch_ratings_recover_legacy_votes_and_count_each_user_once(hints):
    db = DB({"ratings": rating_rows()})
    single = asyncio.run(ratings.get_manga_rating(NATIVE, db=db))
    assert (single["average"], single["count"]) == (3.5, 2)
    batch = asyncio.run(ratings.get_batch_ratings(ratings.BatchRatingsRequest(manga_slugs=[NATIVE]), user=None, db=db))
    assert batch["ratings"][NATIVE] == {"average": 3.5, "count": 2}
    assert len(db.reads) == 2  # One existing DB query per endpoint, not per book.
    assert not db.writes


def test_catalog_ratings_combine_aliases_in_the_existing_batched_query(hints):
    db = DB({"ratings": rating_rows()})
    payload = {"data": {"items": [{"slug": NATIVE}, {"slug": "another-book-2"}]}}
    manga._attach_ratings_to_items(payload, db)
    item = payload["data"]["items"][0]
    assert (item["rating_average"], item["rating_count"]) == (3.5, 2)
    assert len(db.reads) == 1
    assert OLD in db.reads[0][1]["manga_slug"]


def test_top_ratings_merge_the_two_identities_before_ranking(hints):
    db = DB({"ratings": rating_rows()})
    result = asyncio.run(ratings.get_top_rated_manga(limit=24, db=db))
    assert len(result["items"]) == 1
    assert result["items"][0]["manga_slug"] == NATIVE
    assert (result["items"][0]["average"], result["items"][0]["count"]) == (3.5, 2)
    assert len(db.reads) == 1


def test_personal_rating_uses_the_most_recent_alias_and_new_votes_preserve_old_data(hints, monkeypatch):
    db = DB({"ratings": rating_rows()})
    personal = asyncio.run(ratings.get_my_rating(NATIVE, user={"id": "a"}, db=db))
    assert personal["score"] == 3
    assert {OLD, NATIVE} == set(db.reads[-1][1]["manga_slug"])
    monkeypatch.setattr(ratings, "enforce_user_action_limit", lambda *args, **kwargs: None)
    asyncio.run(ratings.rate_manga(None, ratings.RateRequest(manga_slug=NATIVE, score=4), user={"id": "a"}, db=db))
    assert [operation for _, operation, _, _ in db.writes] == ["upsert"]
    assert db.writes[0][2]["manga_slug"] == NATIVE


